#step 8
# missing value & Statistics
missing = df.isnull().sum()  # to count the missing values
print(missing)

#step 9
# missing percentages
missing_percent =(df.isnull().sum()/len(df))*100
print(missing_percent)

df.describe() #show only numerical data

df.describe(include="all") # display only catagorical Data

#P 1.1:Data cleaning
#Step 1 Count Duplicates
duplicate_count=df.duplicated().sum()
print("duplicate rows" , duplicate_count)

# step 2 Veiw duplicates
df[df.duplicated()]

# step 3 Remove duplicates
df_clean =df.drop_duplicates().copy()
print("original shape:" , df.shape)
print("Cleanied shape:" ,df_clean.shape)

# step 4 verify
df_clean.duplicated().sum()

#P 1.2: Handling Missing Value
# optin A- Drop Incomlete Rows /missing value ko drop karna
df_drop=df_clean.dropna().copy()
print("Before:" , df_clean.shape)
print("After:" , df_drop.shape)
# drpna() is simple, but it may discard usuful records. use it only when justified

# missing value ko median se replace karna
# Option B  median value se replace kiya jata hai
# Numercal meadian formula: first term+second term /2
df_clean["salary_package_lpa"] =df_clean["salary_package_lpa"].fillna(df_clean["salary_package_lpa"].median())

# Option C
# missing value ko mean se replace karna
# Numerical mean ,formula: element of the aaray/number of elements
df_clean["placement_status"] =df_clean["placement_status"].fillna(df_clean["placement_status"].mean()
)
print(df_clean)

# Option D
# Catagorical Mode
df_clean["extracurriculars"] =df_clean["extracurriculars"].fillna(df_clean["extracurriculars"].mode()[0])
print(df_clean)
# formula of mode: number of frquency jyada hogi to usko mode maan leng

# final Cleaning Check
print("missing Value:")
print(df_clean.isnull().sum())
print("Duplicate Rows:", df_clean.duplicated().sum())

#Step 6 Spaerate Features and Target
X=df[["cgpa","coding_skills","communication_skills"]]
y=df["placement_status"]

print("Features(X):")
print(X.head())
print("Target(y):")
print(y.head())

print(y.isna().sum())
print(df.isna().sum())

X_train, X_test, y_train, y_test = train_test_split(
    X, y,
    test_size=0.25,   # 25% testing data
    random_state=42
)

print("Training records:", len(X_train))
print("Testing records:", len(X_test))

#Step 8 Feature Scalling and Model Creation
model=Pipeline([
    ("scaler",StandardScaler()),
    ("classifier",LogisticRegression())
])

#Step 9  Train the Model
model.fit(X_train,y_train)
print("Model Training completed.")

#Step 10 Predict the Test Data
y_pred=model.predict(X_test)

comparison =pd.DataFrame({
    'Actual': y_test.values,
    'Predicted': y_pred
})
print(comparison)

#step 12 Classification --> Accuracy, Precision , Recall, F1 Score
accuracy = accuracy_score(y_test, y_pred)
precision=precision_score(y_test,y_pred)
recall=recall_score(y_test,y_pred)
f1=f1_score(y_test,y_pred)

print("Accuracy:",round(accuracy,3))
print("Precision:",round(precision,3))
print("Recall:",round(recall,3))
print("F1 Score:",round(f1,3))

print("\nDetailed Classification Report:")
print(classification_report(
    y_test,y_pred,
    labels=[0,1],
    target_names=["Not_Placed","Placed"],
    zero_division=0
))

# Step 13 understand Prediction Probality probabilty
probabilities=model.predict_proba(X_test)
print("Columns are ordered as classes :",model.classes_)
print(probabilities)

#Step 14  Predict for a new Student
new_student=pd.DataFrame({
    "cgpa":[6.70],
    "coding_skills":[4.6],
    "communication_skills": [4.3]
})
predicted_class=model.predict(new_student)[0]
