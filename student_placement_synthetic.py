#Step 1 import libraries
import pandas as pd # tabular
import numpy as np # numerical
import matplotlib.pyplot as plt # visualization
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler #data ko ek hi standared main rakhna for understanding
from sklearn.linear_model import LogisticRegression #for binary classification
from sklearn.pipeline import Pipeline #for run the code in systmatic way
from sklearn.metrics import (
accuracy_score,precision_score,recall_score,f1_score,confusion_matrix,classification_report) #for evaluation

print("Libraries imported")

# PART B- Dataset Setup
#step 1
df=pd.read_csv("student_placement_synthetic.csv") # read the data
print(df.head())

df.head()

# step 2 inspect the dataset
print("first five rows")
print(df.head())

